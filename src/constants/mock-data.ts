export function getProductAvailability(p: Product): AvailabilityStatus {
  if (!p.inStockSizes || p.inStockSizes.length === 0) return "Contact for Availability";
  if (p.inStockSizes.length < p.sizes.length) return "Limited Stock";
  return "In Stock";
}

