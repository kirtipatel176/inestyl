/**
 * Filter categories that actually contain products, fulfilling Requirement 1:
 * "Only display categories that actually contain products."
 */
export function getAvailableNavSubcategories(
  list: NavSubcategory[],
  genderFilter?: "Men" | "Women",
  typeFilter?: "footwear" | "clothing"
): NavSubcategory[] {
  return list.filter((sub) => {
    return PRODUCTS_DATA.some((p) => {
      // Check gender if required
      if (genderFilter) {
        if (p.gender !== genderFilter && p.gender !== "Unisex") return false;
      }
      // Check type if required
      if (typeFilter) {
        if (p.type !== typeFilter) return false;
      }

      const sLower = sub.name.toLowerCase();
      const pSub = (p.subcategory || "").toLowerCase();
      const pCat = (p.category || "").toLowerCase();
      const pShoeType = (p.shoeType || "").toLowerCase();
      const pClothingCat = (p.clothingCategory || "").toLowerCase();

      return (
        pSub.includes(sLower) ||
        sLower.includes(pSub) ||
        pCat.includes(sLower) ||
        pShoeType.includes(sLower) ||
        pClothingCat.includes(sLower) ||
        (sLower.includes("shoes") && p.type === "footwear")
      );
    });
  });
}

