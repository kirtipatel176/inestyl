// Helper to create variant inventories
function generateVariants(sizes: string[], inStockSizes: string[], colours: { name: string; hex: string }[]): ProductVariant[] {
  const variants: ProductVariant[] = [];
  sizes.forEach((size, sIdx) => {
    colours.forEach((col, cIdx) => {
      const isAvailable = inStockSizes.includes(size);
      variants.push({
        id: `var-${sIdx}-${cIdx}`,
        size,
        colour: col.name,
        stockQuantity: isAvailable ? Math.floor(Math.random() * 4) + 1 : 0,
        isAvailable,
      });
    });
  });
  return variants;
}

